const path=require('node:path'),assert=require('node:assert/strict');
const {chromium}=require(path.join(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES,'playwright'));
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1380,height:960}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file://'+path.resolve(__dirname,'../DesignPreview.html'));
 await page.waitForSelector('#models tr');
 const before=await page.locator('#tokens').innerText();
 await page.locator('#model').selectOption('gpt-6.1-sol');
 assert.notEqual(await page.locator('#tokens').innerText(),before);
 assert.equal(await page.locator('#models tr').count(),1);
 await page.locator('#period').selectOption('90');
 assert.match(await page.locator('#range').innerText(),/주별/);
 await page.locator('#metric').selectOption('runs');
 assert.ok(await page.locator('#legend').evaluate(e=>e.classList.contains('hidden')));
 await page.locator('#model').selectOption('all');
 await page.locator('#period').selectOption('7');
 await page.locator('#metric').selectOption('tokens');
 const oldCalls=await page.locator('#calls').innerText();
 await page.locator('#addDemo').click();
 assert.equal(Number(await page.locator('#calls').innerText()),Number(oldCalls)+1);
 await page.locator('#runTab').click();assert.ok(await page.locator('#history tr').count()>0);
 await page.locator('#callTab').click();
 await page.locator('button[data-page="gen"]').click();
 assert.equal(await page.locator('#chips button').count(),30);
 await page.locator('button[data-page="dash"]').click();
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);assert.equal(overflow,false);
 await page.screenshot({path:'/workspace/scratch/7228662b28fe/dashboard-design-qa.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS preview: ranges, model filter, trend modes, sample call tracking, tabs, 30 chips, no horizontal overflow, no JS errors');
 await browser.close();
})().catch(e=>{console.error(e.message);process.exit(1)});
